def _test_train():
    import torch
    if status.get("model.py") != "ok":
        return "not tested -- needs a working model.py first"
    tr = fresh("text2city.train")
    if tr is None:
        return "doesn't import (error above)"
    torch.manual_seed(0)
    model = tr.TextToCityParams(embedding_dim=384, hidden_dim=32)
    x = torch.randn(32, 384)
    fake = {}
    for p in tr.PARAM_SCHEMA:
        fake[p.name] = (np.random.randint(0, len(p.choices), 32).astype(np.int64) if p.kind == "categorical"
                        else np.random.rand(32).astype(np.float32))
    fake["green_override"] = (fake["green_override"] > 0.5).astype(np.float32)
    weights = {p.name: torch.ones(len(p.choices)) for p in tr.PARAM_SCHEMA if p.kind == "categorical"}
    opt = torch.optim.Adam(model.parameters(), lr=1e-2)
    first = tr.compute_loss(model(x), fake, weights).item()
    for _ in range(40):
        loss = tr.compute_loss(model(x), fake, weights)
        opt.zero_grad(); loss.backward(); opt.step()
    if not loss.item() < first * 0.7:
        return f"loss doesn't go down ({first:.2f} -> {loss.item():.2f}) (TODO 7)"


