import shutil


def find_blender():
    exe = shutil.which("blender")
    if exe:
        return exe
    candidates = ["/Applications/Blender.app/Contents/MacOS/Blender",
                  "/usr/bin/blender", "/usr/local/bin/blender", "/snap/bin/blender"]
    candidates += [str(p) for p in Path("/Applications").glob("Blender*/Contents/MacOS/Blender")]
    for base in (r"C:\Program Files\Blender Foundation", r"C:\Program Files (x86)\Blender Foundation"):
        if Path(base).exists():
            candidates += [str(p) for p in Path(base).glob("Blender*/blender.exe")]
    return next((c for c in candidates if Path(c).exists()), None)


BLENDER = find_blender()       # or set it by hand, e.g. "/Applications/Blender.app/Contents/MacOS/Blender"
